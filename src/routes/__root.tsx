function RootShell({ children }: { children: ReactNode }) {
  return (
    <html lang="en">
      <head>
        <HeadContent />
      </head>
      <body>
        {children}
        <Scripts />
      </body>
    </html>
  );
}

function SiteHeader() {
  const { user } = useAuth();
  return (
    <header className="relative z-20 border-b border-border/60 backdrop-blur">
      <div className="mx-auto flex max-w-6xl items-center justify-between gap-4 px-4 py-4">
        <Link to="/" className="font-display text-lg tracking-tight">
          Astro<span className="aurora-text">Postdoc</span>Radar
        </Link>
        <nav className="flex items-center gap-4 text-sm">
          <Link to="/" activeProps={{ className: "text-primary" }} className="hover:text-primary">
            Browse
          </Link>
          <Link
            to="/saved"
            activeProps={{ className: "text-primary" }}
            className="hover:text-primary"
          >
            Shortlist
          </Link>
          {user ? (
            <button
              className="text-muted-foreground hover:text-foreground"
              onClick={() => supabase.auth.signOut()}
            >
              Sign out
            </button>
          ) : (
            <Link to="/auth" className="hover:text-primary">
              Sign in
            </Link>
          )}
        </nav>
      </div>
    </header>
  );
}

function RootComponent() {
  const { queryClient } = Route.useRouteContext();

  return (
    <QueryClientProvider client={queryClient}>
      <div className="starfield" aria-hidden="true" />
      <SiteHeader />
      {/* Required: nested routes render here. Removing <Outlet /> breaks all child routes. */}
      <Outlet />
      <footer className="relative z-10 border-t border-border/60 py-8 text-center text-xs text-muted-foreground">
        Listings are collected from public sources. Always confirm details on the original page.
      </footer>
      <Toaster position="top-right" />
    </QueryClientProvider>
  );
}

